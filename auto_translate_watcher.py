    # Run once
    process_file()
    
    # Start watching only if --watch argument is provided
    if len(sys.argv) > 1 and sys.argv[1] == "--watch":
        print("\n[Mode Watch] Watching for changes in index.html & Note_de_Position...")
        path_to_watch = os.path.dirname(HTML_SOURCE)
        event_handler = FileChangeHandler()
        observer = Observer()
        observer.schedule(event_handler, path=path_to_watch, recursive=False)
        observer.start()
        
        try:
            while True:
                time.sleep(1)
        except KeyboardInterrupt:
            observer.stop()
        observer.join()
    else:
        print("\n[Done] One-shot translation and sync completed successfully. Exiting.")
